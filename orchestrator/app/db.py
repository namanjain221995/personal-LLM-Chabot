def insert_web_claims(rows: List[dict]) -> int:
    """Persist resolved claims from one research run. Returns rows written."""
    if not rows:
        return 0
    now = _now()
    written = 0
    with connection() as con:
        for r in rows:
            claim = _text(str(r.get("claim") or "")).strip()
            if not claim:
                continue
            con.execute(
                "INSERT INTO web_claims (research_id, page_id, url, subquestion, "
                "claim, value, as_of, kind, confidence, created_at) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)",
                (
                    _text(str(r.get("research_id") or "")),
                    r.get("page_id"),
                    _text(str(r.get("url") or ""))[:2000],
                    _text(str(r.get("subquestion") or ""))[:1000],
                    claim[:2000],
                    _text(str(r.get("value") or ""))[:1000],
                    r.get("as_of"),
                    _text(str(r.get("kind") or "unknown"))[:20],
                    float(r.get("confidence") or 0.0),
                    now,
                ),
            )
            written += 1
    return written


def search_web_claims(terms: str, limit: int = 5, kinds: Optional[List[str]] = None) -> List[dict]:
    """Claims whose text matches the question's words, best match first.

    `websearch_to_tsquery` takes what a person types and never raises on
    punctuation; ranking prefers the closer match, then the newer claim."""
    query = (terms or "").strip()
    if not query:
        return []
    wanted = list(kinds or ["current"])
    with connection() as con:
        rows = con.execute(
            """SELECT c.id, c.research_id, c.url, c.subquestion, c.claim, c.value,
                      c.as_of, c.kind, c.confidence, c.created_at,
                      p.domain, p.authority, p.published_at,
                      ts_rank_cd(c.search_tsv, websearch_to_tsquery('english', %s)) AS rank
                 FROM web_claims c
                 LEFT JOIN web_pages p ON p.id = c.page_id
                WHERE c.search_tsv @@ websearch_to_tsquery('english', %s)
                  AND c.kind = ANY(%s)
                ORDER BY rank DESC, c.created_at DESC
                LIMIT %s""",
            (query, query, wanted, int(limit)),
        ).fetchall()
    return [dict(r) for r in rows]


