def update_conversation(
    user_id: int,
    conversation_id: str,
    title: Optional[str] = None,
    pinned: Optional[bool] = None,
    archived: Optional[bool] = None,
) -> Optional[dict]:
    """Update any subset of {title, pinned, archived}; None means "leave alone".

    Only a rename counts as activity: pinning or archiving sets the flag and
    nothing else, so a chat keeps its place in the updated_at ordering when it
    comes back out of the archive (V3-DESIGN §1). Returns None when the
    conversation is missing or owned by someone else.
    """
    assignments: List[str] = []
    values: List[object] = []
    if title is not None:
        # A rename is an act of ownership: mark the title 'user' so the
        # auto-titler can never overwrite it, on this device or any other.
        assignments += ["title = %s", "title_source = 'user'", "updated_at = %s"]
        values += [_text(title), _now()]
    if pinned is not None:
        assignments.append("pinned = %s")
        values.append(bool(pinned))
    if archived is not None:
        assignments.append("archived = %s")
        values.append(bool(archived))
    if not assignments:  # nothing to change — just an ownership-scoped read
        return get_conversation(user_id, conversation_id)
    with connection() as con:
        # RETURNING makes this one round trip instead of an UPDATE followed by
        # a SELECT, and closes the window where another tab could change the
        # row between the two.
        row = con.execute(
            f"UPDATE conversations SET {', '.join(assignments)} "
            "WHERE id = %s AND user_id = %s "
            "RETURNING id, title, created_at, updated_at, pinned, archived",
            (*values, conversation_id, user_id),
        ).fetchone()
    return _conversation_dict(row) if row else None


