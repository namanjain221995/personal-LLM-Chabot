# V6 (2026-08-21): cross-chat memory for the assistant.
#
# `user_facts` is the explicit fact store — durable statements the user made
# ("Sahil Patel is the CEO of TechSara") extracted by a background model call
# and injected into future prompts, the way ChatGPT's Memory works. Facts are
# plain rows the user can list and delete; nothing is fine-tuned.
#
# `message_embeddings` powers semantic cross-chat recall: one vector per
# stored chat message (same Qwen3-Embedding service and packed-float32 format
