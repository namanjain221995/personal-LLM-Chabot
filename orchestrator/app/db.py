#: Versions kept per page. Enough to see a fact change hands twice; small
#: enough that a daily-changing news front page cannot grow without bound.
_MAX_PAGE_VERSIONS = 5


def upsert_web_page(
    url_key: str,
    url: str,
    canonical_url: str,
    title: str,
    text: str,
    content_type: str,
    fetch_status: int,
    content_hash: str,
    links: Optional[List[str]] = None,
    *,
    published_at: Optional[datetime] = None,
    modified_at: Optional[datetime] = None,
    source_type: str = "",
    authority: int = 0,
    etag: str = "",
    last_modified: str = "",
) -> dict:
    """Store (or refresh) one fetched page, globally deduped by `url_key`.

    Returns {"id", "changed", "previous_hash"}. `changed` is the re-store
    signal the owner asked for: the same URL fetched again with a DIFFERENT
    content hash means the site moved on, so the vector index must re-chunk it
    (indexed_at is reset to NULL exactly then). An unchanged hash only bumps
    the freshness clock — no re-embedding, no index churn.

    V14: provenance rides in (dates the page states about itself, its
    structural source class, the cached authority) and a CHANGED page's
    previous text is preserved in web_page_versions before it is replaced —
    a change over time stays distinguishable from a contradiction.
    """
    now = _now()
    from .core.provenance import domain_of as _domain_of

    domain = _domain_of(url) or ""
    with connection() as con:
        prev = con.execute(
            "SELECT id, content_hash, title, text, published_at, fetched_at "
            "FROM web_pages WHERE url_key = %s",
            (url_key,),
        ).fetchone()
        previous_hash = prev["content_hash"] if prev else None
        changed = previous_hash is not None and previous_hash != content_hash
        if changed and (prev.get("text") or "").strip():
            # Keep what the page USED to say. Written before the update so a
            # crash between the two leaves the old version, never nothing.
            con.execute(
                "INSERT INTO web_page_versions (page_id, content_hash, title, "
                "text, published_at, fetched_at, superseded_at) "
                "VALUES (%s, %s, %s, %s, %s, %s, %s)",
                (
                    int(prev["id"]),
                    _text(previous_hash or ""),
                    _text(prev.get("title") or ""),
                    _text(prev.get("text") or ""),
                    prev.get("published_at"),
                    prev.get("fetched_at") or now,
                    now,
                ),
            )
            con.execute(
                "DELETE FROM web_page_versions WHERE page_id = %s AND id NOT IN ("
                "SELECT id FROM web_page_versions WHERE page_id = %s "
                "ORDER BY superseded_at DESC, id DESC LIMIT %s)",
                (int(prev["id"]), int(prev["id"]), _MAX_PAGE_VERSIONS),
            )
        row = con.execute(
            "INSERT INTO web_pages (url_key, url, canonical_url, title, text, "
            "content_type, fetch_status, content_hash, links, fetch_count, "
            "first_seen_at, fetched_at, indexed_at, published_at, modified_at, "
            "last_changed_at, source_type, authority, domain, etag, last_modified) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, 1, %s, %s, NULL, "
            "%s, %s, %s, %s, %s, %s, %s, %s) "
            "ON CONFLICT (url_key) DO UPDATE SET "
            "url = EXCLUDED.url, canonical_url = EXCLUDED.canonical_url, "
            "title = EXCLUDED.title, text = EXCLUDED.text, "
            "content_type = EXCLUDED.content_type, "
            "fetch_status = EXCLUDED.fetch_status, "
            "content_hash = EXCLUDED.content_hash, "
            "links = EXCLUDED.links, "
            "fetch_count = web_pages.fetch_count + 1, "
            "fetched_at = EXCLUDED.fetched_at, "
            # A changed page must be re-indexed; an unchanged one keeps its
            # vectors exactly as they are.
            "indexed_at = CASE WHEN web_pages.content_hash = EXCLUDED.content_hash "
            "THEN web_pages.indexed_at ELSE NULL END, "
            # Dates are facts the page states; a page that stops stating one
            # does not un-publish itself, so a known value is never erased.
            "published_at = COALESCE(EXCLUDED.published_at, web_pages.published_at), "
            "modified_at = COALESCE(EXCLUDED.modified_at, web_pages.modified_at), "
            "last_changed_at = CASE WHEN web_pages.content_hash = EXCLUDED.content_hash "
            "THEN web_pages.last_changed_at ELSE EXCLUDED.last_changed_at END, "
            "source_type = CASE WHEN EXCLUDED.source_type <> '' "
            "THEN EXCLUDED.source_type ELSE web_pages.source_type END, "
            "authority = CASE WHEN EXCLUDED.authority > 0 "
            "THEN EXCLUDED.authority ELSE web_pages.authority END, "
            "domain = CASE WHEN EXCLUDED.domain <> '' THEN EXCLUDED.domain ELSE web_pages.domain END, "
            "etag = CASE WHEN EXCLUDED.etag <> '' THEN EXCLUDED.etag ELSE web_pages.etag END, "
            "last_modified = CASE WHEN EXCLUDED.last_modified <> '' "
            "THEN EXCLUDED.last_modified ELSE web_pages.last_modified END "
            "RETURNING id",
            (
                _text(url_key),
                _text(url),
                _text(canonical_url),
                _text(title),
                # The one param that skipped _text() — and the largest
                # untrusted one. A NUL survives utf-8 decoding (text/plain,
                # PDF text layers), PostgreSQL rejects it, and the DataError
                # aborted whole crawls (review round, 2026-08-30).
                _text(text or ""),
                _text(content_type),
                int(fetch_status),
                _text(content_hash),
                [_text(l) for l in (links or [])][:500],
                now,
                now,
                published_at,
                modified_at,
                now,
                _text(source_type or ""),
                int(authority or 0),
                _text(domain),
                _text(etag or "")[:200],
                _text(last_modified or "")[:100],
            ),
        ).fetchone()
        return {"id": int(row["id"]), "changed": changed, "previous_hash": previous_hash}


