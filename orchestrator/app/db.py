def share_for_conversation(conversation_id: str) -> Optional[dict]:
    """The ACTIVE share for a conversation, or None. Owner-facing."""
    with connection() as con:
        row = con.execute(
            """SELECT s.*, v.version_number, v.message_count, v.last_message_id,
                      v.created_at AS version_created_at
                 FROM conversation_shares s
                 LEFT JOIN conversation_share_versions v ON v.id = s.current_version
                WHERE s.conversation_id = %s AND s.status = 'active'""",
            (conversation_id,),
        ).fetchone()
    return dict(row) if row else None


def share_by_public_id(public_id: str) -> Optional[dict]:
    """The row a public link addresses, with its live payload.

    Returns the share whatever its status: the CALLER decides what a revoked
    or expired share means, so that every failure can be answered
    identically. Distinguishing them here would leak which links ever existed.
    """
    with connection() as con:
        row = con.execute(
            """SELECT s.id, s.public_id, s.secret_hash, s.visibility, s.status,
                      s.expires_at, s.workspace_id, s.show_owner_name,
                      s.created_at, v.payload, v.version_number
                 FROM conversation_shares s
                 LEFT JOIN conversation_share_versions v ON v.id = s.current_version
                WHERE s.public_id = %s""",
            (public_id,),
        ).fetchone()
    return dict(row) if row else None


def create_share(
    *,
    conversation_id: str,
    workspace_id: str,
    created_by: int,
    public_id: str,
    secret_hash: str,
    visibility: str,
    expires_at: Optional[datetime],
    show_owner_name: bool,
    payload: dict,
    content_hash: str,
    last_message_id: Optional[int],
    message_count: int,
) -> Optional[dict]:
    """Create a share and its first version, atomically.

    Returns None when an active share already exists — the partial unique
    index decides that, not a prior SELECT, so two clicks racing each other
    cannot both win.
    """
    now = _now()
    with connection() as con:
        try:
            share = con.execute(
                """INSERT INTO conversation_shares
                       (conversation_id, workspace_id, created_by, public_id,
                        secret_hash, visibility, status, show_owner_name,
                        expires_at, created_at, updated_at)
                   VALUES (%s, %s, %s, %s, %s, %s, 'active', %s, %s, %s, %s)
                   ON CONFLICT DO NOTHING
                   RETURNING id""",
                (conversation_id, workspace_id, created_by, public_id, secret_hash,
                 visibility, show_owner_name, expires_at, now, now),
            ).fetchone()
            if share is None:
                return None
            share_id = int(share["id"])
            version = con.execute(
                """INSERT INTO conversation_share_versions
                       (share_id, version_number, payload, content_hash,
                        last_message_id, message_count, created_by, created_at)
                   VALUES (%s, 1, %s, %s, %s, %s, %s, %s)
                   RETURNING id""",
                (share_id, _json_param(payload), content_hash, last_message_id,
                 message_count, created_by, now),
            ).fetchone()
            con.execute(
                "UPDATE conversation_shares SET current_version = %s WHERE id = %s",
                (int(version["id"]), share_id),
            )
        except Exception:
            raise
    return share_for_conversation(conversation_id)


def add_share_version(
    *,
    share_id: int,
    payload: dict,
    content_hash: str,
    last_message_id: Optional[int],
    message_count: int,
    created_by: int,
) -> int:
    """Publish a new version and switch to it in one transaction.

    The switch is the last statement, so a failure anywhere leaves the OLD
    version live. A half-published snapshot is the one outcome that must not
    exist: it would show a page nobody reviewed.
    """
    now = _now()
    with connection() as con:
        row = con.execute(
            """INSERT INTO conversation_share_versions
                   (share_id, version_number, payload, content_hash,
                    last_message_id, message_count, created_by, created_at)
               SELECT %s,
                      coalesce(max(version_number), 0) + 1,
                      %s, %s, %s, %s, %s, %s
                 FROM conversation_share_versions WHERE share_id = %s
               RETURNING id""",
            (share_id, _json_param(payload), content_hash, last_message_id,
             message_count, created_by, now, share_id),
        ).fetchone()
        version_id = int(row["id"])
        con.execute(
            "UPDATE conversation_shares SET current_version = %s, updated_at = %s "
            "WHERE id = %s",
            (version_id, now, share_id),
        )
    return version_id


def update_share_settings(
    share_id: int,
    *,
    visibility: Optional[str] = None,
    expires_at: Optional[datetime] = None,
    clear_expiry: bool = False,
    show_owner_name: Optional[bool] = None,
) -> None:
    sets, params = ["updated_at = %s"], [_now()]
    if visibility is not None:
        sets.append("visibility = %s"); params.append(visibility)
    if clear_expiry:
        sets.append("expires_at = NULL")
    elif expires_at is not None:
        sets.append("expires_at = %s"); params.append(expires_at)
    if show_owner_name is not None:
        sets.append("show_owner_name = %s"); params.append(show_owner_name)
    params.append(share_id)
    with connection() as con:
        con.execute(
            f"UPDATE conversation_shares SET {', '.join(sets)} WHERE id = %s",
            tuple(params),
        )


