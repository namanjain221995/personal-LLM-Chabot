def enqueue_web_crawl(
    conversation_id: str,
    root_url: str,
    scope_prefix: str,
    kind: str = "share",
    max_pages: int = 0,
    max_minutes: float = 0.0,
    priority: int = 0,
    recent_hours: float = 24.0,
) -> Optional[int]:
    """Queue a bounded background crawl of one site. → the job id, or None
    when the same scope is already queued/running or was crawled within
    `recent_hours` (a shared link is not a reason to re-read a site read this
    morning)."""
    with connection() as con:
        existing = con.execute(
            "SELECT id FROM web_crawls WHERE scope_prefix = %s AND ("
            "status IN ('queued', 'running') OR (status IN ('done', 'capped') "
            "AND finished_at IS NOT NULL AND finished_at > now() - make_interval(secs => %s)))"
            " ORDER BY id DESC LIMIT 1",
            (_text(scope_prefix), float(recent_hours) * 3600.0),
        ).fetchone()
        if existing:
            return None
        row = con.execute(
            "INSERT INTO web_crawls (conversation_id, root_url, scope_prefix, "
            "status, started_at, kind, max_pages, max_minutes, priority) "
            "VALUES (%s, %s, %s, 'queued', %s, %s, %s, %s, %s) RETURNING id",
            (
                _text(conversation_id or ""),
                _text(root_url),
                _text(scope_prefix),
                _now(),
                _text(kind or "share")[:20],
                int(max_pages or 0),
                float(max_minutes or 0.0),
                int(priority or 0),
            ),
        ).fetchone()
        return int(row["id"])


def next_queued_web_crawl() -> Optional[dict]:
    """Claim the next queued job (highest priority, oldest first) and mark it
    running. SKIP LOCKED keeps two workers from claiming the same row."""
    with connection() as con:
        row = con.execute(
            "WITH picked AS (SELECT id FROM web_crawls WHERE status = 'queued' "
            "ORDER BY priority DESC, id LIMIT 1 FOR UPDATE SKIP LOCKED) "
            "UPDATE web_crawls w SET status = 'running', started_at = %s "
            "FROM picked WHERE w.id = picked.id "
            "RETURNING w.id, w.conversation_id, w.root_url, w.scope_prefix, "
            "w.kind, w.max_pages, w.max_minutes, w.priority",
            (_now(),),
        ).fetchone()
    return dict(row) if row else None


def requeue_interrupted_web_crawls() -> int:
    """At startup: a background job left 'running' by a restart goes back to
    the queue (stored pages make the resume nearly free); a foreground crawl
    cut off the same way is closed as 'capped' — its conversation's follow-up
    Q&A only trusts done/capped crawls, and 'running' forever hid its pages."""
    with connection() as con:
        requeued = con.execute(
            "UPDATE web_crawls SET status = 'queued' "
            "WHERE status = 'running' AND kind <> 'manual' RETURNING id"
        ).fetchall()
        con.execute(
            "UPDATE web_crawls SET status = 'capped', finished_at = %s, "
            "detail = 'interrupted by a restart' "
            "WHERE status = 'running' AND kind = 'manual'",
            (_now(),),
        )
    return len(requeued)


