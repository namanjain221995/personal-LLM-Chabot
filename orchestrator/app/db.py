def messages_missing_embeddings(
    user_id: int, model_id: str, limit: int = 64, min_chars: int = 15
) -> List[dict]:
    """Newest stored chat messages that have no embedding row yet.

    Newest-first so fresh conversations become searchable immediately; the
    older backlog drains a batch per request.
    """
    with connection() as con:
        rows = con.execute(
            "SELECT m.id, m.conversation_id, m.role, m.content"
            "  FROM messages m JOIN conversations c ON c.id = m.conversation_id"
            " WHERE c.user_id = %s AND m.role IN ('user', 'assistant')"
            "   AND length(m.content) >= %s"
            "   AND NOT EXISTS (SELECT 1 FROM message_embeddings e"
            "                    WHERE e.message_id = m.id AND e.model_id = %s)"
            " ORDER BY m.id DESC LIMIT %s",
            (user_id, min_chars, model_id, limit),
        ).fetchall()
    return [
        {
            "id": int(r["id"]),
            "conversation_id": r["conversation_id"],
            "role": r["role"],
            "content": r["content"],
        }
        for r in rows
    ]


def store_message_embeddings(
    user_id: int, model_id: str, dim: int, rows: List[dict]
) -> int:
    """Insert packed-float32 vectors; racing duplicates are ignored."""
    if not rows:
        return 0
    now = _now()
    with connection() as con:
        cur = con.cursor()
        cur.executemany(
            "INSERT INTO message_embeddings"
            " (message_id, user_id, conversation_id, model_id, dim, embedding,"
            "  created_at)"
            " VALUES (%s, %s, %s, %s, %s, %s, %s)"
            " ON CONFLICT (message_id, model_id) DO NOTHING",
            [
                (
                    r["message_id"],
                    user_id,
                    r["conversation_id"],
                    model_id,
                    dim,
                    r["embedding"],
                    now,
                )
                for r in rows
            ],
        )
        inserted = cur.rowcount
    return max(inserted, 0)


def fetch_message_embeddings(
    user_id: int,
    model_id: str,
    exclude_conversation_id: Optional[str],
    limit: int = 500,
) -> List[dict]:
    """Embedding candidates from the user's OTHER conversations, newest first.

    Scoped to the owner inside the statement like every accessor here; the
    current conversation is excluded because within-chat context is already
    in the prompt.
    """
    with connection() as con:
        rows = con.execute(
            "SELECT e.message_id, e.conversation_id, e.embedding,"
            "       m.role, m.content, c.title"
            "  FROM message_embeddings e"
            "  JOIN messages m ON m.id = e.message_id"
            "  JOIN conversations c ON c.id = e.conversation_id"
            " WHERE e.user_id = %s AND e.model_id = %s"
            "   AND e.conversation_id <> %s"
            " ORDER BY e.message_id DESC LIMIT %s",
            (user_id, model_id, exclude_conversation_id or "", limit),
        ).fetchall()
    return [
        {
            "message_id": int(r["message_id"]),
            "conversation_id": r["conversation_id"],
            "embedding": bytes(r["embedding"]),
            "role": r["role"],
            "content": r["content"],
            "title": r["title"],
        }
        for r in rows
    ]


def web_corpus_counts() -> dict:
    """Size, embedding backlog and refresh backlog of the public web corpus.

    One query rather than three: this runs on every Prometheus scrape.
    """
    with connection() as con:
        row = con.execute(
            """SELECT count(*) AS pages,
                      count(*) FILTER (WHERE indexed_at IS NULL) AS pending,
                      count(*) FILTER (WHERE next_refresh_at IS NOT NULL
                                         AND next_refresh_at <= now()) AS due
                 FROM web_pages"""
        ).fetchone()
    return {
        "pages": int(row["pages"]) if row else 0,
        "pending": int(row["pending"]) if row else 0,
        "due": int(row["due"]) if row else 0,
    }


